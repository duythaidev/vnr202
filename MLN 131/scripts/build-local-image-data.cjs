// Chạy lại sau khi đổi imageUrl, block image hoặc thay file ảnh.
// node scripts/build-local-image-data.cjs
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'museum-3d-single-02.js'), 'utf8') + '\n' + fs.readFileSync(path.join(root, 'museum-3d-single-03.js'), 'utf8') + '\nresult={pieces:MUSEUM_PIECES,stories:STORY_DATA};', context);
const {pieces, stories} = context.result;
const files = [...new Set([...pieces.map(p => p.imageUrl), ...Object.values(stories).flatMap(s => s.steps.flatMap(step => step.blocks.filter(b => b.type === 'image').map(b => b.src)))])].filter(src => src && !/^(https?:|data:)/i.test(src));
const map = {};
for (const src of files) {
    const absolute = path.resolve(root, src);
    if (!absolute.startsWith(root + path.sep)) throw new Error('Image outside course: ' + src);
    const mime = {'.svg':'image/svg+xml','.webp':'image/webp','.png':'image/png','.jpg':'image/jpeg','.jpeg':'image/jpeg'}[path.extname(absolute).toLowerCase()];
    if (!mime) throw new Error('Unsupported image: ' + src);
    map[src] = 'data:' + mime + ';base64,' + fs.readFileSync(absolute).toString('base64');
}
fs.writeFileSync(path.join(root, 'museum-image-data.js'), '// Generated by scripts/build-local-image-data.cjs. Local-file-safe textures.\nconst MUSEUM_LOCAL_IMAGES = Object.freeze(' + JSON.stringify(map) + ');\n');
console.log('Packed ' + files.length + ' local images for file://.');
